function conf = ConflictDegree(PopObj)
% ConflictDegree - 计算Spearman冲突度（模块①辅助函数）
%
% 功能概述：
%   对每个目标，计算它与其他目标的平均"冲突程度"
%   使用 Spearman 秩相关系数来衡量目标间的关系
%
% 什么是Spearman秩相关系数？
%   - 衡量两个变量的单调关系强度
%   - 范围 [-1, 1]
%   - ρ = +1：完全正相关（一个变大，另一个也变大）
%   - ρ = -1：完全负相关（一个变大，另一个变小）
%   - ρ = 0：无单调关系
%   - 与Pearson相关不同，Spearman对非线性单调关系也有效
%
% 冲突度的含义：
%   conf(j) = mean(1 - |ρ_j,others|)
%   - |ρ| 接近 1 → 高度相关 → 冲突度低（信息冗余）
%   - |ρ| 接近 0 → 不相关 → 冲突度高
%   - ρ 为负 → 负相关 → 冲突度最高
%
% 为什么不用Pearson相关？
%   Spearman对单调变换不敏感，无需预处理目标值
%   例如：f1=x², f2=x，Pearson可能不高，但Spearman很高
%
% 输入：
%   PopObj - N×M 矩阵，N个解的M个目标值
%            例如：100个解，5个目标 → 100×5 矩阵
%
% 输出：
%   conf   - M×1 向量，各目标的冲突度，范围 [0, 1]
%            冲突度越高，表示该目标与其他目标越"对立"
%
% 调用示例：
%   PopObj = rand(100, 5);  % 100个解，5个目标
%   conf = ConflictDegree(PopObj);  % 5×1 冲突度向量

    M = size(PopObj, 2);  % 目标数量
    conf = zeros(M, 1);   % 初始化输出

    % 特殊情况：只有1个目标，无法计算冲突度
    if M < 2
        return;
    end

    % ===================================================================
    % 计算 Spearman 秩相关矩阵
    % ===================================================================
    % corr(..., 'type', 'Spearman') 计算 M×M 的Spearman相关矩阵
    % rho(i,j) 表示目标i和目标j的Spearman相关系数
    % 对角线 rho(i,i) = 1（自己和自己完全相关）
    rho = corr(PopObj, 'type', 'Spearman');

    % 处理特殊情况：如果某目标是常数（所有解的该目标值相同），
    % corr 会返回 NaN，这里将其替换为 0
    rho(isnan(rho)) = 0;

    % 取绝对值：|ρ|
    % 因为正相关和负相关都表示有关系，只是方向不同
    % 我们关心的是"相关强度"，不是"相关方向"
    rho_abs = abs(rho);

    % ===================================================================
    % 计算每个目标的冲突度
    % ===================================================================
    for j = 1:M
        % others = 除目标j外的所有目标索引
        others = setdiff(1:M, j);  % 例如 M=5, j=2 → others=[1,3,4,5]

        % 冲突度 = mean(1 - |ρ_j,others|)
        % 1 - |ρ| 表示"不相关的程度"
        % 对所有其他目标取平均
        conf(j) = mean(1 - rho_abs(j, others));
    end
end
