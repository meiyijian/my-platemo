function [pathInfo, pathCleanup] = GGPSetupPaths()
%GGPSETUPPATHS Add PlatEMO and the audited label-validation code to path.
%   [PATHINFO, PATHCLEANUP] = GGPSETUPPATHS() returns path locations and an
%   onCleanup object that restores the caller's original MATLAB path.

    experimentDirectory = fileparts(mfilename("fullpath"));
    experimentsDirectory = fileparts(experimentDirectory);
    platemoDirectory = fileparts(experimentsDirectory);
    repositoryDirectory = fileparts(platemoDirectory);
    labelAuditDirectory = fullfile(experimentsDirectory, ...
        "REMO_new2_AdaMaO_UniformMix_LabelValidation");

    requiredFiles = [ ...
        fullfile(labelAuditDirectory, "algorithms", "LVUniformMixAudit_Hybrid.m"), ...
        fullfile(labelAuditDirectory, "ReconstructFutureLabelOutcomes.m"), ...
        fullfile(labelAuditDirectory, "results", "stage1", "equivalence_passed.txt")];
    missingFiles = requiredFiles(~arrayfun(@isfile, requiredFiles));
    if ~isempty(missingFiles)
        error("GGP:MissingAuditDependency", ...
            "The validated label-audit dependency is incomplete. Missing: %s", ...
            strjoin(missingFiles, ", "));
    end

    originalPath = path();
    pathCleanup = onCleanup(@() path(originalPath));
    addpath(genpath(repositoryDirectory));
    rehash();

    equivalenceText = strtrim(string(fileread(requiredFiles(3))));
    if equivalenceText ~= "PASS"
        error("GGP:EquivalenceGateFailed", ...
            "The label-audit search-equivalence gate is not PASS: %s", requiredFiles(3));
    end

    requiredSymbols = [ ...
        "LVUniformMixAudit_Hybrid", ...
        "ReconstructFutureLabelOutcomes", ...
        "REMO_new2_AdaMaO_SDEOnly_UniformMix_Original"];
    for symbol = requiredSymbols
        if isempty(which(symbol))
            error("GGP:UnresolvedDependency", ...
                "Required MATLAB symbol is not on the path: %s", symbol);
        end
    end

    pathInfo = struct( ...
        "ExperimentDirectory", experimentDirectory, ...
        "RepositoryDirectory", repositoryDirectory, ...
        "PlatEMODirectory", platemoDirectory, ...
        "LabelAuditDirectory", labelAuditDirectory, ...
        "EquivalenceEvidence", requiredFiles(3));
end
