function config = GGPProtocol(profile, problemSet)
%GGPPROTOCOL Define the frozen Good-group Precision experiment protocol.
%   CONFIG = GGPPROTOCOL(PROFILE, PROBLEMSET) returns the problem matrix,
%   algorithm parameters, and independent-run jobs for PROFILE. Supported
%   profiles are "smoke", "pilot", and "formal". PROBLEMSET is "all" by
%   default; "original" retains the frozen five-problem protocol used by
%   the isolated DualPBI complementarity supplement. The all-problem formal
%   profile contains 10 problems x 2 objective counts x 25 fixed seeds =
%   500 jobs. Extension problems are appended so that original problem
%   indices and fixed seeds remain unchanged.

    if nargin < 1 || isempty(profile)
        profile = "formal";
    end
    if nargin < 2 || isempty(problemSet)
        problemSet = "all";
    end
    profile = validatestring(string(profile), ["smoke", "pilot", "formal"]);
    problemSet = validatestring(string(problemSet), ["all", "original"]);

    allProblems = struct( ...
        "Name", {"DTLZ2", "DTLZ4", "DTLZ7", "WFG3", "WFG7", ...
        "DTLZ3", "DTLZ5", "DTLZ6", "WFG1", "WFG8"}, ...
        "Family", {"DTLZ", "DTLZ", "DTLZ", "WFG", "WFG", ...
        "DTLZ", "DTLZ", "DTLZ", "WFG", "WFG"}, ...
        "RequestedD", {30, 30, 30, 30, 30, 30, 30, 30, 30, 30}, ...
        "ExpectedActualD", {30, 30, 30, 31, 30, 30, 30, 30, 30, 30});
    if problemSet == "original"
        problems = allProblems(1:5);
    else
        problems = allProblems;
    end

    parameters = struct( ...
        "gmax", 3000, ...
        "pMix", 0.50, ...
        "rGood", 0.25, ...
        "qKeep", 0.80, ...
        "lambda0", 0.35, ...
        "nMin", 4, ...
        "nMax", 6);

    switch profile
        case "smoke"
            selectedProblems = 4;
            objectiveCounts = 2;
            runNumbers = 1;
            requestedD = 3;
            populationSize = 20;
            maxFE = 36;
            gmax = 1;
        case "pilot"
            selectedProblems = 1;
            objectiveCounts = 10;
            runNumbers = 1:2;
            requestedD = 30;
            populationSize = 100;
            maxFE = 300;
            gmax = 300;
        case "formal"
            selectedProblems = 1:numel(problems);
            objectiveCounts = [10, 20];
            runNumbers = 1:25;
            requestedD = 30;
            populationSize = 100;
            maxFE = 500;
            gmax = parameters.gmax;
        otherwise
            error("GGP:UnknownProfile", "Unsupported profile: %s", profile);
    end

    numberOfJobs = numel(selectedProblems)*numel(objectiveCounts)*numel(runNumbers);
    emptyJob = struct( ...
        "ProblemIndex", 0, ...
        "Problem", "", ...
        "Family", "", ...
        "M", 0, ...
        "RequestedD", 0, ...
        "ExpectedActualD", 0, ...
        "N", 0, ...
        "MaxFE", 0, ...
        "Gmax", 0, ...
        "Run", 0, ...
        "Seed", 0, ...
        "PairedKey", "");
    jobs = repmat(emptyJob, numberOfJobs, 1);

    jobIndex = 0;
    for problemIndex = selectedProblems
        problem = problems(problemIndex);
        for objectiveCount = objectiveCounts
            for runNumber = runNumbers
                jobIndex = jobIndex + 1;
                actualRequestedD = problem.RequestedD;
                expectedActualD = problem.ExpectedActualD;
                if profile == "smoke"
                    actualRequestedD = requestedD;
                    expectedActualD = requestedD;
                end
                jobs(jobIndex) = struct( ...
                    "ProblemIndex", problemIndex, ...
                    "Problem", problem.Name, ...
                    "Family", problem.Family, ...
                    "M", objectiveCount, ...
                    "RequestedD", actualRequestedD, ...
                    "ExpectedActualD", expectedActualD, ...
                    "N", populationSize, ...
                    "MaxFE", maxFE, ...
                    "Gmax", gmax, ...
                    "Run", runNumber, ...
                    "Seed", GGPStableSeed(problemIndex, objectiveCount, runNumber), ...
                    "PairedKey", sprintf("%s_M%d_run%03d", ...
                        problem.Name, objectiveCount, runNumber));
            end
        end
    end

    config = struct( ...
        "SchemaVersion", 2, ...
        "Profile", profile, ...
        "Problems", problems, ...
        "Parameters", parameters, ...
        "StageEdges", [0, 0.25, 0.50, 0.75, 1.00], ...
        "Jobs", jobs);
end
