function [pathInfo, pathCleanup] = DPCSetupPaths()
%DPCSetupPaths - Add validated complementarity experiment dependencies
%   pathInfo = DPCSetupPaths() adds the PlatEMO repository and returns
%   the resolved experiment directories.
%
%   [pathInfo,pathCleanup] = DPCSetupPaths() also returns an ONCLEANUP
%   object that restores the original MATLAB path.
%
%   See also GGPSetupPaths, run_DualPBIComplementarity

    supplementDirectory = fileparts(mfilename("fullpath"));
    experimentDirectory = fileparts(supplementDirectory);
    experimentsDirectory = fileparts(experimentDirectory);
    platemoDirectory = fileparts(experimentsDirectory);
    repositoryDirectory = fileparts(platemoDirectory);
    labelAuditDirectory = fullfile(experimentsDirectory, ...
        "REMO_new2_AdaMaO_UniformMix_LabelValidation");

    requiredFiles = [ ...
        fullfile(experimentDirectory, "GGPProtocol.m"), ...
        fullfile(experimentDirectory, "GGPValidateRunFile.m"), ...
        fullfile(labelAuditDirectory, "algorithms", ...
            "LVUniformMixAudit_Hybrid.m"), ...
        fullfile(labelAuditDirectory, ...
            "ReconstructFutureLabelOutcomes.m"), ...
        fullfile(labelAuditDirectory, "results", "stage1", ...
            "equivalence_passed.txt")];
    missingFiles = requiredFiles(~arrayfun(@isfile, requiredFiles));
    if ~isempty(missingFiles)
        error("DPC:MissingDependency", ...
            "Complementarity dependency is missing: %s", ...
            strjoin(missingFiles, ", "));
    end

    originalPath = path();
    pathCleanup = onCleanup(@() path(originalPath));
    addpath(genpath(repositoryDirectory));
    rehash();

    evidenceFile = requiredFiles(end);
    equivalenceText = strtrim(string(fileread(evidenceFile)));
    if equivalenceText ~= "PASS"
        error("DPC:EquivalenceGateFailed", ...
            "The frozen search equivalence evidence is not PASS: %s", ...
            evidenceFile);
    end

    pathInfo = struct( ...
        "SupplementDirectory", supplementDirectory, ...
        "ExperimentDirectory", experimentDirectory, ...
        "ExperimentsDirectory", experimentsDirectory, ...
        "PlatEMODirectory", platemoDirectory, ...
        "RepositoryDirectory", repositoryDirectory, ...
        "LabelAuditDirectory", labelAuditDirectory, ...
        "EquivalenceEvidence", evidenceFile, ...
        "DefaultResultRoot", fullfile(supplementDirectory, "results"), ...
        "DefaultSourceResultRoot", fullfile(experimentDirectory, "results"));
end

