function [valid,report] = CMCValidateRunFile( ...
        filePath,protocol,job,expectedUpstreamHash)
%CMCVALIDATERUNFILE Validate one staged CMC result MAT.

    if nargin < 4
        expectedUpstreamHash = "";
    end
    valid = false;
    report = struct('Detail',"",'IGD',NaN,'IGDp',NaN,'Runtime',NaN);
    if ~isfile(filePath)
        report.Detail = "file does not exist";
        return;
    end
    try
        data = load(filePath,'metadata','finalPopulation','IGD','IGDp', ...
            'anytimeIGDpAUC','anytimeTrace','runtime','activityRows', ...
            'snapshotRows','referenceRows');
    catch exception
        report.Detail = "load failed: " + string(exception.message);
        return;
    end
    required = ["metadata","finalPopulation","IGD","IGDp","runtime", ...
        "anytimeIGDpAUC","anytimeTrace","activityRows", ...
        "snapshotRows","referenceRows"];
    if ~all(isfield(data,required)) || ~isstruct(data.metadata)
        report.Detail = "required MAT variables are missing";
        return;
    end
    fields = ["SchemaVersion","ProtocolVersion","ProtocolHash", ...
        "Stage","Profile","Problem","Family","M","RequestedD", ...
        "ActualD","N","Run","Arm","ArmID","AlgorithmClass","CompletedFE", ...
        "MaxFE","SearchSeed","RoutingSeed","RandomControlSeed", ...
        "JobID","PairedKey","Runtime","UpstreamDecisionHash", ...
        "EndpointSaveCount","AnytimeIGDpDefinition", ...
        "MATLABVersion","Computer","HostName"];
    if ~all(isfield(data.metadata,fields))
        report.Detail = "metadata fields are incomplete";
        return;
    end
    checks = data.metadata.SchemaVersion == protocol.SchemaVersion && ...
        string(data.metadata.ProtocolVersion) == protocol.ProtocolVersion && ...
        string(data.metadata.ProtocolHash) == protocol.ProtocolHash && ...
        string(data.metadata.Stage) == protocol.Stage && ...
        string(data.metadata.Profile) == protocol.Profile && ...
        string(data.metadata.Problem) == job.Problem && ...
        string(data.metadata.Family) == job.Family && ...
        data.metadata.M == job.M && data.metadata.Run == job.Run && ...
        data.metadata.RequestedD == job.RequestedD && ...
        data.metadata.ActualD == job.ActualD && ...
        data.metadata.N == protocol.N && ...
        string(data.metadata.Arm) == job.Arm && ...
        data.metadata.ArmID == job.ArmID && ...
        string(data.metadata.AlgorithmClass) == job.AlgorithmClass && ...
        data.metadata.CompletedFE == data.metadata.MaxFE && ...
        data.metadata.CompletedFE == protocol.MaxFE && ...
        data.metadata.SearchSeed == job.SearchSeed && ...
        data.metadata.RoutingSeed == job.RoutingSeed && ...
        data.metadata.RandomControlSeed == job.RandomControlSeed;
    checks = checks && string(data.metadata.JobID) == job.JobID && ...
        string(data.metadata.PairedKey) == job.PairedKey && ...
        data.metadata.EndpointSaveCount == protocol.EndpointSaveCount && ...
        string(data.metadata.AnytimeIGDpDefinition) == ...
            protocol.AnytimeIGDpDefinition && ...
        string(data.metadata.MATLABVersion) == ...
            protocol.ExecutionEnvironment.MATLABVersion && ...
        string(data.metadata.Computer) == ...
            protocol.ExecutionEnvironment.Computer && ...
        string(data.metadata.HostName) == ...
            protocol.ExecutionEnvironment.HostName;
    if strlength(string(expectedUpstreamHash)) > 0
        checks = checks && string(data.metadata.UpstreamDecisionHash) == ...
            string(expectedUpstreamHash);
    elseif protocol.Stage == "stage0"
        checks = checks && strlength( ...
            string(data.metadata.UpstreamDecisionHash)) == 0;
    end
    if ~checks
        report.Detail = "metadata does not match the frozen job";
        return;
    end
    if ~isstruct(data.finalPopulation) || ...
            ~all(isfield(data.finalPopulation,["Dec","Obj","Con"])) || ...
            size(data.finalPopulation.Dec,2) ~= job.ActualD || ...
            size(data.finalPopulation.Obj,2) ~= job.M || ...
            size(data.finalPopulation.Dec,1) ~= ...
                size(data.finalPopulation.Obj,1) || ...
            ~isscalar(data.IGD) || ~isfinite(data.IGD) || data.IGD < 0 || ...
            ~isscalar(data.IGDp) || ~isfinite(data.IGDp) || data.IGDp < 0 || ...
            ~isscalar(data.anytimeIGDpAUC) || ...
            ~isfinite(data.anytimeIGDpAUC) || data.anytimeIGDpAUC < 0 || ...
            ~isscalar(data.runtime) || ~isfinite(data.runtime) || data.runtime < 0
        report.Detail = "final population or endpoint metrics are invalid";
        return;
    end
    runtimeTolerance = 1e-12*max(1,abs(data.runtime));
    if ~isscalar(data.metadata.Runtime) || ...
            abs(data.metadata.Runtime-data.runtime) > runtimeTolerance
        report.Detail = "metadata runtime does not match the stored runtime";
        return;
    end
    try
        recomputedAUC = CMCTraceAUC(data.anytimeTrace);
    catch exception
        report.Detail = "invalid anytime trace: " + string(exception.message);
        return;
    end
    aucTolerance = 1e-12*max(1,abs(data.anytimeIGDpAUC));
    expectedRatio = data.anytimeTrace.FE(:)./protocol.MaxFE;
    expectedTraceRows = height(data.anytimeTrace);
    if protocol.StageNumber >= 2
        expectedTraceRows = protocol.EndpointSaveCount;
    end
    if height(data.anytimeTrace) ~= expectedTraceRows || ...
            any(abs(data.anytimeTrace.FERatio(:)-expectedRatio) > 1e-12) || ...
            data.anytimeTrace.FE(end) ~= protocol.MaxFE || ...
            abs(data.anytimeTrace.FERatio(end)-1) > 1e-12 || ...
            abs(data.anytimeTrace.IGDp(end)-data.IGDp) > ...
                1e-12*max(1,abs(data.IGDp)) || ...
            abs(recomputedAUC-data.anytimeIGDpAUC) > aucTolerance
        report.Detail = "anytime trace does not reproduce the stored AUC";
        return;
    end
    if ~istable(data.activityRows) || ~istable(data.snapshotRows) || ...
            ~istable(data.referenceRows)
        report.Detail = "audit outputs must be tables";
        return;
    end
    activitySchema = CMCActivitySchema();
    snapshotSchema = CMCSnapshotSchema();
    referenceSchema = CMCReferenceSchema();
    if ~all(ismember(activitySchema.Properties.VariableNames, ...
            data.activityRows.Properties.VariableNames)) || ...
            ~all(ismember(snapshotSchema.Properties.VariableNames, ...
            data.snapshotRows.Properties.VariableNames)) || ...
            ~all(ismember(referenceSchema.Properties.VariableNames, ...
            data.referenceRows.Properties.VariableNames))
        report.Detail = "audit table columns are incomplete";
        return;
    end
    if protocol.Stage == "stage0"
        if ~validActivityContract(data.activityRows)
            report.Detail = "Stage 0 activity rows violate the factor contract";
            return;
        end
    end
    if protocol.Stage == "stage1" && ...
            (isempty(data.snapshotRows) || isempty(data.referenceRows))
        report.Detail = "Stage 1 counterfactual tables are empty";
        return;
    end
    if protocol.Stage == "stage1" && ~validSnapshotContract( ...
            data.snapshotRows,data.referenceRows,protocol)
        report.Detail = "Stage 1 snapshot rows violate the checkpoint contract";
        return;
    end
    report.Detail = "PASS";
    report.IGD = data.IGD;
    report.IGDp = data.IGDp;
    report.Runtime = data.runtime;
    valid = true;
end

function valid = validActivityContract(rows)
    expected = ["P","Q","K","C","D","E_GEN","E_FINAL", ...
        "F","G","P_ERR_GATE"];
    valid = ~isempty(rows) && mod(height(rows),numel(expected)) == 0;
    if ~valid
        return;
    end
    generations = unique(rows.Generation);
    for generation = generations(:)'
        observed = sort(rows.Factor(rows.Generation == generation));
        valid = valid && isequal(observed,sort(expected(:)));
    end
end

function valid = validSnapshotContract(snapshots,references,protocol)
    expectedRules = ["FINAL_MATCHED","ACCUM_MATCHED","EXP_NO_Q", ...
        "EXP_NO_C","EXP_NO_D","EXP_SIMPLE_FULL","EXP_FULL", ...
        "IND_RELATION_ONLY","IND_FULL","SHUFFLED_D","SHUFFLED_F", ...
        "EXP_NO_PERR_GATE","ORACLE_GREEDY","RANDOM_MATCHED"];
    expectedIDs = (1:numel(protocol.Checkpoints))';
    observedIDs = sort(unique(references.SnapshotID));
    valid = height(references) == numel(expectedIDs) && ...
        isequal(observedIDs,expectedIDs) && ...
        isequal(sort(unique(snapshots.SnapshotID)),expectedIDs) && ...
        ~any(snapshots.CountedTowardFE) && ...
        all(snapshots.OfflineCandidateEvaluations > 0);
    if ~valid
        return;
    end
    for snapshotID = expectedIDs'
        observedRules = sort(unique(snapshots.Rule( ...
            snapshots.SnapshotID == snapshotID)));
        valid = valid && isequal(observedRules,sort(expectedRules(:)));
    end
end
