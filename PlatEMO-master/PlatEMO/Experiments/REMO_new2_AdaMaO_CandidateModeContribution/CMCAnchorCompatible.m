function pass = CMCAnchorCompatible(armDecision,protocol)
%CMCANCHORCOMPATIBLE Check fixed-factor host noninferiority to CURRENT_HCV.

    row = armDecision(armDecision.Arm == "CURRENT_HCV",:);
    required = ["CI95Upper","MaxMCI95Upper", ...
        "MaxFamilyMGeoMeanRatio","DTLZGeoMeanRatio", ...
        "WFGGeoMeanRatio","MaxFamilyMSevereRegressionCount","Cells"];
    if isempty(row) || ~all(ismember(required, ...
            string(armDecision.Properties.VariableNames)))
        pass = false;
        return;
    end
    pass = isfinite(row.CI95Upper(1)) && ...
        row.Cells(1) == numel(protocol.Problems)*numel(protocol.Objectives) && ...
        row.CI95Upper(1) <= protocol.Thresholds.NonInferiorityMargin && ...
        row.MaxMCI95Upper(1) <= ...
            protocol.Thresholds.NonInferiorityMargin && ...
        row.MaxFamilyMGeoMeanRatio(1) <= ...
            protocol.Thresholds.NonInferiorityMargin && ...
        row.DTLZGeoMeanRatio(1) <= ...
            protocol.Thresholds.NonInferiorityMargin && ...
        row.WFGGeoMeanRatio(1) <= ...
            protocol.Thresholds.NonInferiorityMargin && ...
        row.MaxFamilyMSevereRegressionCount(1) <= ...
            protocol.Thresholds.MaxSevereRegressionCount;
end
