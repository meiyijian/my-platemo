function protocol = CMCProtocol(stage,profile)
%CMCPROTOCOL Return the frozen staged candidate-mode protocol.

    stage = normalizeStage(stage);
    if nargin < 2 || strlength(string(profile)) == 0
        profile = defaultProfile(stage);
    end
    profile = lower(string(profile));

    protocol = struct();
    protocol.SchemaVersion = 2;
    protocol.ProtocolVersion = "CMC-2026-08-24-v2";
    protocol.Stage = stage;
    protocol.StageNumber = stageNumber(stage);
    protocol.Profile = profile;
    protocol.RequestedD = 30;
    protocol.N = 100;
    protocol.Parameters = struct( ...
        'gmax',3000,'pMix',0.50,'rGood',0.25,'qKeep',0.80, ...
        'lambda0',0.35,'nMin',4,'nMax',6,'nHarm',2,'wConFlag',0);
    protocol.Checkpoints = [0.20 0.50 0.80];
    protocol.RandomReplicates = 500;
    protocol.ReferenceSizes = [4096 8192 16384];
    protocol.Thresholds = thresholds();
    protocol.EndpointSaveCount = double(protocol.StageNumber >= 2)*4;
    protocol.AnytimeIGDpDefinition = ...
        "TRAPEZOID_MEAN_FROM_FIRST_OBSERVED_FE_TO_MAXFE";
    protocol.FrozenHostHashes = [ ...
        "BD51B71976C31AD8172B00A6675A73710C475689A6906B4FDD70D10E0A920566", ...
        "ABE4DD8ED74157C544899AFA73136F95851DB913CB6B14DFA3B09BABE725AED0"];
    protocol.ExecutionEnvironment = struct( ...
        'MATLABVersion',string(version), ...
        'Computer',string(computer), ...
        'HostName',currentHostName());
    protocol.ComponentHashes = componentHashes();

    if profile == "smoke"
        protocol.Problems = ["DTLZ2","WFG3"];
        protocol.Objectives = 3;
        protocol.RequestedD = 6;
        protocol.Runs = 1;
        protocol.MaxFE = 83;
        protocol.Parameters.gmax = 24;
        protocol.Checkpoints = 0.75;
        protocol.RandomReplicates = 20;
        protocol.ReferenceSizes = [64 128 256];
    else
        switch stage
            case "stage0"
                requireProfile(profile,"pilot");
                protocol.Problems = ["DTLZ2","DTLZ7","WFG3","WFG7"];
                protocol.Objectives = [10 20];
                protocol.Runs = 1:3;
                protocol.MaxFE = 500;
            case "stage1"
                requireProfile(profile,"pilot");
                protocol.Problems = ["DTLZ2","DTLZ4","DTLZ7", ...
                    "WFG3","WFG4","WFG7"];
                protocol.Objectives = [10 20];
                protocol.Runs = 1:5;
                protocol.MaxFE = 500;
            case "stage2"
                requireProfile(profile,"screening");
                protocol.Problems = ["DTLZ2","DTLZ4","DTLZ7", ...
                    "WFG3","WFG4","WFG7"];
                protocol.Objectives = 10;
                protocol.Runs = 1:10;
                protocol.MaxFE = 500;
            case "stage3"
                requireProfile(profile,"formal");
                protocol.Problems = [compose("DTLZ%d",1:7), ...
                    compose("WFG%d",1:9)];
                protocol.Objectives = [10 20];
                protocol.Runs = 1:30;
                protocol.MaxFE = 500;
        end
    end

    protocol.StageFolder = stageFolder(stage);
    protocol.Previous = previousStage(stage,profile);
    protocol.CanonicalText = canonicalText(protocol);
    protocol.ProtocolHash = CMCTextHash(protocol.CanonicalText);
end

function value = currentHostName()
    value = string(getenv('COMPUTERNAME'));
    if strlength(value) == 0
        value = string(getenv('HOSTNAME'));
    end
    if strlength(value) == 0
        value = string(computer);
    end
end

function value = thresholds()
    value = struct( ...
        'DirectMCID',0.05, ...
        'EndpointMCIDRatio',0.98, ...
        'NonInferiorityMargin',1.05, ...
        'SevereRegressionRatio',1.20, ...
        'MaxSevereRegressionCount',1, ...
        'BootstrapSamples',10000, ...
        'BootstrapSeed',20260824, ...
        'SignFlipSamples',20000, ...
        'SignFlipSeed',20260825, ...
        'Alpha',0.05, ...
        'ActivityRate',0.10, ...
        'MaxOverlapAtK',0.90, ...
        'ReferenceSpearman',0.95, ...
        'ReferenceJaccard',0.90, ...
        'UtilityTolerance',1e-12);
end

function textValue = canonicalText(p)
    t = p.Thresholds;
    componentNames = string(fieldnames(p.ComponentHashes));
    componentValues = string(struct2cell(p.ComponentHashes));
    componentParts = componentNames+"="+componentValues;
    textValue = strjoin([string(p.SchemaVersion),p.ProtocolVersion, ...
        p.Stage,p.Profile,p.ExecutionEnvironment.MATLABVersion, ...
        p.ExecutionEnvironment.Computer,p.ExecutionEnvironment.HostName, ...
        strjoin(p.Problems,","),join(string(p.Objectives),","), ...
        join(string(p.Runs),","),string(p.RequestedD),string(p.N), ...
        string(p.MaxFE), ...
        string(p.Parameters.gmax),string(p.Parameters.pMix), ...
        string(p.Parameters.rGood),string(p.Parameters.qKeep), ...
        string(p.Parameters.lambda0),string(p.Parameters.nMin), ...
        string(p.Parameters.nMax),string(p.Parameters.nHarm), ...
        string(p.Parameters.wConFlag),join(string(p.Checkpoints),","), ...
        string(p.RandomReplicates),join(string(p.ReferenceSizes),","), ...
        string(t.DirectMCID),string(t.EndpointMCIDRatio), ...
        string(t.NonInferiorityMargin),string(t.SevereRegressionRatio), ...
        string(t.MaxSevereRegressionCount),string(t.BootstrapSamples), ...
        string(t.BootstrapSeed),string(t.SignFlipSamples), ...
        string(t.SignFlipSeed),string(t.Alpha),string(t.ActivityRate), ...
        string(t.MaxOverlapAtK), ...
        string(t.ReferenceSpearman),string(t.ReferenceJaccard), ...
        string(t.UtilityTolerance),string(p.EndpointSaveCount), ...
        p.AnytimeIGDpDefinition,join(p.FrozenHostHashes,","), ...
        join(componentParts,",")],"|");
end

function value = componentHashes()
