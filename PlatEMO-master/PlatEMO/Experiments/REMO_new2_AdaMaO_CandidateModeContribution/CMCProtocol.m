        "WARMUP","SNAPSHOT_AUDIT","TRACE_AUC","SIGN_FLIP", ...
        "ANCHOR_GATE","STAGE2_GATE","STAGE3_GATE", ...
        "FACTOR_BASE","CORE","ARM_CONFIG","CANDIDATE_SELECTION", ...
        "ACTIVITY_SCHEMA","SNAPSHOT_SCHEMA","REFERENCE_SCHEMA"];
    files = string({ ...
        fullfile(root,'CMCProtocol.m'); ...
        fullfile(root,'CMCArmCatalog.m'); ...
        fullfile(root,'run_CandidateModeContribution.m'); ...
        fullfile(root,'analyze_CandidateModeContribution.m'); ...
        fullfile(root,'CMCValidateRunFile.m'); ...
        fullfile(root,'CMCRequirePreviousGate.m'); ...
        fullfile(root,'CMCTableFingerprint.m'); ...
        fullfile(root,'CMCVerifySourceTwin.m'); ...
        fullfile(root,'CMCWarmupLearningToolboxes.m'); ...
        fullfile(root,'CMCBuildSnapshotAudit.m'); ...
        fullfile(root,'CMCTraceAUC.m'); ...
        fullfile(root,'CMCHierarchicalSignFlipP.m'); ...
        fullfile(root,'CMCAnchorCompatible.m'); ...
        fullfile(root,'CMCStage2GateCode.m'); ...
        fullfile(root,'CMCStage3GateCode.m'); ...
        fullfile(root,'algorithms','CMC_HCV_FactorBase.m'); ...
        fullfile(root,'algorithms','CMC_HCV_Core.m'); ...
        fullfile(root,'algorithms','private','CMCArmConfiguration.m'); ...
        fullfile(root,'algorithms','private','CMCCandidateSelection.m'); ...
        fullfile(root,'CMCActivitySchema.m'); ...
        fullfile(root,'CMCSnapshotSchema.m'); ...
        fullfile(root,'CMCReferenceSchema.m')});
    value = struct();
    for index = 1:numel(files)
        if ~isfile(files(index))
            error('CMC:MissingProtocolComponent', ...
                'Frozen protocol component is missing: %s.',files(index));
        end
        value.(char(labels(index))) = CMCTextHash(fileread(files(index)));
    end
    value.ALGORITHMS_TREE = treeHash(fullfile(root,'algorithms'));
    value.EXPERIMENT_TREE = treeHash(root,"tests/");
    helperFiles = string({fullfile(root,'CMCBootstrapMeanCI.m'); ...
        fullfile(root,'CMCComparePaired.m'); ...
        fullfile(root,'CMCHolmAdjust.m'); ...
        fullfile(root,'CMCResolveArms.m'); ...
