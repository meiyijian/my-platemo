        fullfile(root,'CMCStableSeed.m'); ...
        fullfile(root,'CMCBuildActivityRows.m'); ...
        fullfile(root,'CMCSummarizeEvidenceFactors.m')});
    helperParts = strings(numel(helperFiles),1);
    for index = 1:numel(helperFiles)
        relativePath = replace(erase(string(helperFiles(index)), ...
            string(root)+filesep),"\","/");
        helperParts(index) = relativePath+"="+ ...
            CMCTextHash(fileread(helperFiles(index)));
    end
    value.ANALYSIS_HELPERS = CMCTextHash(strjoin(helperParts,newline));
end

function value = treeHash(root,excludedPrefixes)
    if nargin < 2
        excludedPrefixes = strings(0,1);
    end
    listing = dir(fullfile(root,'**','*.m'));
    relative = strings(numel(listing),1);
    for index = 1:numel(listing)
        fullPath = fullfile(listing(index).folder,listing(index).name);
        relative(index) = replace(string(fullPath),string(root)+filesep,"");
    end
    relative = replace(relative,"\","/");
    keep = true(size(relative));
    for prefix = string(excludedPrefixes(:))'
        keep = keep & ~startsWith(lower(relative),lower(prefix));
    end
    relative = relative(keep);
    listing = listing(keep);
    [relative,order] = sort(relative);
    listing = listing(order);
    parts = strings(numel(listing),1);
    for index = 1:numel(listing)
        fullPath = fullfile(listing(index).folder,listing(index).name);
        parts(index) = relative(index)+"="+CMCTextHash(fileread(fullPath));
    end
    value = CMCTextHash(strjoin(parts,newline));
end

function info = previousStage(stage,profile)
    info = struct('Stage',"",'Profile',"");
    if stage == "stage1"
        info.Stage = "stage0";
        info.Profile = profile;
    elseif stage == "stage2"
        info.Stage = "stage1";
        info.Profile = ternary(profile == "smoke","smoke","pilot");
    elseif stage == "stage3"
        info.Stage = "stage2";
        info.Profile = ternary(profile == "smoke","smoke","screening");
    end
end

function value = ternary(condition,a,b)
    if condition
        value = a;
    else
        value = b;
    end
end

function profile = defaultProfile(stage)
    values = struct('stage0',"pilot",'stage1',"pilot", ...
        'stage2',"screening",'stage3',"formal");
    profile = values.(char(stage));
end

function requireProfile(actual,expected)
    if actual ~= expected
        error('CMC:UnknownProfile', ...
            'Stage profile must be %s or smoke, not %s.',expected,actual);
    end
end

function stage = normalizeStage(value)
    stage = lower(string(value));
    aliases = containers.Map({'0','1','2','3'}, ...
        {'stage0','stage1','stage2','stage3'});
    if isKey(aliases,char(stage))
        stage = string(aliases(char(stage)));
    end
    if ~ismember(stage,["stage0","stage1","stage2","stage3"])
        error('CMC:UnknownStage','Unknown CMC stage: %s.',stage);
    end
end

function number = stageNumber(stage)
    number = find(["stage0","stage1","stage2","stage3"] == stage,1)-1;
end

function folder = stageFolder(stage)
    folders = ["stage0_activity","stage1_counterfactual", ...
        "stage2_screening","stage3_formal"];
    folder = folders(stageNumber(stage)+1);
end
