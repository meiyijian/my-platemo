function paths = CMCStagePaths(protocol,resultRoot)
%CMCSTAGEPATHS Resolve raw, analysis, manifest, and log directories.

    if nargin < 2 || strlength(string(resultRoot)) == 0
        setup = CMCSetupPaths();
        resultRoot = setup.DefaultResultRoot;
    end
    stageRoot = fullfile(char(resultRoot),char(protocol.StageFolder));
    paths = struct( ...
        'ResultRoot',char(resultRoot), ...
        'StageRoot',stageRoot, ...
        'RawRoot',fullfile(stageRoot,'raw',char(protocol.Profile)), ...
        'AnalysisRoot',fullfile(stageRoot,'analysis',char(protocol.Profile)), ...
        'ManifestRoot',fullfile(stageRoot,'manifests',char(protocol.Profile)), ...
        'LogRoot',fullfile(stageRoot,'logs',char(protocol.Profile)));
end
