function config = LTGGPProtocol(profile, problemSet)
%LTGGPPROTOCOL Define the frozen Lambdat030 Good-group Precision protocol.
%   CONFIG = LTGGPPROTOCOL(PROFILE, PROBLEMSET) returns the problem matrix,
%   algorithm parameters, and independent-run jobs for PROFILE. Supported
%   profiles are "smoke", "pilot", and "formal". PROBLEMSET is "all" by
%   default; "original" retains the frozen five-problem matrix used by
%   PWGGP. The problem indices and the seed formula match PWGGP exactly,
%   so every formal run pairs with the existing lambda_t = 0.50 PWGGP
%   results for shared problems.
%
%   Formal selection (2026-09-16): DTLZ2, DTLZ4, DTLZ5 with M = 10/20,
%   25 runs each = 150 jobs. The choice and its evidence live in
%   SELECTED_PROBLEMS.md.

    if nargin < 1 || isempty(profile)
        profile = "formal";
    end
    if nargin < 2 || isempty(problemSet)
        problemSet = "all";
    end
    profile = validatestring(string(profile), ["smoke", "pilot", "formal"]);
    problemSet = validatestring(string(problemSet), ["all", "original"]);

    allProblems = struct( ...
        "Name", {"DTLZ2", "DTLZ4", "DTLZ7", "WFG3", "WFG7", ...
        "DTLZ3", "DTLZ5", "DTLZ6", "WFG1", "WFG8"}, ...
        "Family", {"DTLZ", "DTLZ", "DTLZ", "WFG", "WFG", ...
        "DTLZ", "DTLZ", "DTLZ", "WFG", "WFG"}, ...
        "RequestedD", {30, 30, 30, 30, 30, 30, 30, 30, 30, 30}, ...
        "ExpectedActualD", {30, 30, 30, 31, 30, 30, 30, 30, 30, 30});
    if problemSet == "original"
        problems = allProblems(1:5);
    else
        problems = allProblems;
    end

    parameters = struct( ...
        "gmax", 3000, ...
        "pMix", 0.50, ...
        "rGood", 0.25, ...
        "qKeep", 0.70, ...
        "nMax", 6);

    switch profile
        case "smoke"
            selectedProblems = 4;
            objectiveCounts = 2;
            runNumbers = 1;
            requestedD = 3;
            populationSize = 20;
            maxFE = 36;
            gmax = 1;
        case "pilot"
            selectedProblems = 1;
            objectiveCounts = 10;
            runNumbers = 1:2;
            requestedD = 30;
            populationSize = 100;
            maxFE = 300;
            gmax = 300;
        case "formal"
            selectedProblems = find(ismember(string({problems.Name}), ["DTLZ2","DTLZ4","DTLZ5"]));
            objectiveCounts = [10, 20];
            runNumbers = 1:25;
            requestedD = 30;
            populationSize = 100;
            maxFE = 500;
            gmax = parameters.gmax;
        otherwise
            error("LTGGP:UnknownProfile", "Unsupported profile: %s", profile);
    end

    numberOfJobs = numel(selectedProblems)*numel(objectiveCounts)*numel(runNumbers);
    emptyJob = struct( ...
        "ProblemIndex", 0, ...
        "Problem", "", ...
        "Family", "", ...
        "M", 0, ...
        "RequestedD", 0, ...
        "ExpectedActualD", 0, ...
        "N", 0, ...
        "MaxFE", 0, ...
        "Gmax", 0, ...
        "Run", 0, ...
        "Seed", 0, ...
        "PairedKey", "");
    jobs = repmat(emptyJob, numberOfJobs, 1);

    jobIndex = 0;
    for problemIndex = selectedProblems
        problem = problems(problemIndex);
        for objectiveCount = objectiveCounts
            for runNumber = runNumbers
                jobIndex = jobIndex + 1;
                actualRequestedD = problem.RequestedD;
                expectedActualD = problem.ExpectedActualD;
                if profile == "smoke"
                    actualRequestedD = requestedD;
                    expectedActualD = requestedD;
                end
                jobs(jobIndex) = struct( ...
                    "ProblemIndex", problemIndex, ...
                    "Problem", problem.Name, ...
                    "Family", problem.Family, ...
                    "M", objectiveCount, ...
                    "RequestedD", actualRequestedD, ...
                    "ExpectedActualD", expectedActualD, ...
                    "N", populationSize, ...
                    "MaxFE", maxFE, ...
                    "Gmax", gmax, ...
                    "Run", runNumber, ...
                    "Seed", LTGGPStableSeed(problemIndex, objectiveCount, runNumber), ...
                    "PairedKey", sprintf("%s_M%d_run%03d", ...
                        problem.Name, objectiveCount, runNumber));
            end
        end
    end

    config = struct( ...
        "SchemaVersion", 2, ...
        "Profile", profile, ...
        "Problems", problems, ...
        "Parameters", parameters, ...
        "StageEdges", [0, 0.25, 0.50, 0.75, 1.00], ...
        "Jobs", jobs);
end
