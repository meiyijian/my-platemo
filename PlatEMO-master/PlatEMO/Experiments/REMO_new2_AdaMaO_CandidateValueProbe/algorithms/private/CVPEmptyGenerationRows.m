function rows = CVPEmptyGenerationRows(count)
%CVPEMPTYGENERATIONROWS Preallocated per-generation record for the probe.
%   ROWS = CVPEMPTYGENERATIONROWS() returns a 0x1 struct array with the
%   frozen field set. ROWS = CVPEMPTYGENERATIONROWS(COUNT) returns COUNT
%   rows initialised to NaN / false.

    if nargin < 1
        count = 0;
    end

    template = struct( ...
        'Generation', NaN, ...
        'FEBefore', NaN, ...
        'FEAfter', NaN, ...
        'Ratio', NaN, ...
        'KEff', NaN, ...
        'BatchSize', NaN, ...
        'ArchiveSizeBefore', NaN, ...
        'ArchiveSizeAfter', NaN, ...
        'PopulationSize', NaN, ...
        'ArchiveOverN', NaN, ...
        'SurvivorCount', NaN, ...
        'SurvivalRate', NaN, ...
        'UsedFallback', false, ...
        'TruncatedBatch', false, ...
        ... % --- selection trace ---
        'Mode', "", ...
        'AttemptedMode', "", ...
        'PoolUniqueCount', NaN, ...
        'PoolRawCount', NaN, ...
        'LastRoundUniqueCount', NaN, ...
        'RoundCount', NaN, ...
        'RetainedCount', NaN, ...
        'SelectedK', NaN, ...
        'PErr', NaN, ...
        'LambdaT', NaN, ...
        'IndicatorAvailable', false, ...
        'IndicatorOperational', false, ...
        'FinalAggregationWeighted', false, ...
        'AggregationEligible', NaN, ...
        'AggregationChanged', NaN, ...
        'BatchSpreadNormalized', NaN, ...
        'SelectedFromLastRound', NaN, ...
        ... % --- oracle diagnostic ---
        'OracleValid', false, ...
        'OracleHitCount', NaN, ...
        'OracleHitRate', NaN, ...
        'OracleAlgorithmK', NaN, ...
        'OracleK', NaN, ...
        'OracleBaselineCoverage', NaN, ...
        'OracleAlgorithmCoverage', NaN, ...
        'OracleOracleCoverage', NaN, ...
        'OracleAlgorithmGain', NaN, ...
        'OracleOracleGain', NaN, ...
        'OracleGainRatio', NaN, ...
        'OraclePoolConsidered', NaN, ...
        'OraclePoolTotal', NaN, ...
        'OracleSubsampled', false);

    if count == 0
        rows = repmat(template, 0, 1);
    else
        rows = repmat(template, count, 1);
    end
end
