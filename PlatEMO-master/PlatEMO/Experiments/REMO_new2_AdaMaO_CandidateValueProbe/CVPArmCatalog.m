function catalog = CVPArmCatalog()
%CVPARMCATALOG Frozen five-arm candidate-selection ladder.
%   Every arm shares ONE host (identical framework, HPC labels, k_eff,
%   inner-loop GA, indicator training and environmental selection). Arms
%   differ ONLY in the final candidate-selection rule, so the ladder is a
%   single-factor ablation.
%
%   V0_REMO_RULE is the original REMO selection rule (last inner round only,
%   score>3.9 else top-4) transplanted into the shared host. It is NOT the
%   literal REMO algorithm: it keeps the host's HPC labels and k_eff. The
%   literal-REMO IGD anchor already exists in the two-module ablation
%   tables; this arm exists to isolate the pooling+threshold factor while
%   holding the label layer fixed.

    arms = [ ...
        "V0_REMO_RULE"; ...
        "V1_POOL_ONLY"; ...
        "V2_EXPLORE_ONLY"; ...
        "V3_INDICATOR_ONLY"; ...
        "V4_FULL"];
    armIDs = [0; 1; 2; 3; 4];
    pools = [ ...
        "last_round"; ...
        "accumulated"; ...
        "accumulated"; ...
        "accumulated"; ...
        "accumulated"];
    routes = [ ...
        "remo_threshold"; ...
        "relation_topk"; ...
        "explore"; ...
        "indicator"; ...
        "pmix_draw"];
    batchPolicies = [ ...
        "variable_4_to_pool"; ...
        "fixed_nMax"; ...
        "fixed_nMax"; ...
        "fixed_nMax"; ...
        "fixed_nMax"];
    isolatedFactors = [ ...
        "original-paper selection rule (pool + 3.9 threshold)"; ...
        "candidate pooling only"; ...
        "prediction ambiguity + decision-space dispersion"; ...
        "SDE indicator reranking"; ...
        "pMix mixture of both branches"];
    descriptions = [ ...
        "最后一代候选池，score>3.9 否则 top-4，批量可变"; ...
        "累积候选池上的纯关系 top-nMax（池化效应对照）"; ...
        "累积池 + 模糊度奖励 + qKeep 保留 + 决策空间分散贪心"; ...
        "累积池 + 关系粗筛 30% + SVR 指标重排 top-nMax"; ...
        "累积池 + 每代按 pMix 抽签在 explore/indicator 间选择"];

    catalog = table(armIDs, arms, pools, routes, batchPolicies, ...
        isolatedFactors, descriptions, ...
        'VariableNames', {'ArmID', 'Arm', 'Pool', 'Route', ...
        'BatchPolicy', 'IsolatedFactor', 'Description'});
end
