function S = LabelValidationSchema()
%LabelValidationSchema Central definition of the MAT schema and enums.
%   S = LabelValidationSchema() returns the current schema version, the
%   frozen DirectionSource enumeration and the CandidateMode strings used
%   by every Stage-1 result MAT. Schema version is an integer; bump it only
%   when the on-disk contract changes incompatibly.

    S.version = 1;

    S.directionSource = struct( ...
        'ND_KMEANS',                1, ...
        'UNIFORM_LOW_M_OR_N',       2, ...
        'UNIFORM_FRONT_TOO_SMALL',  3, ...
        'UNIFORM_ZERO_RANGE',       4, ...
        'UNIFORM_NDSORT_FAILURE',   5, ...
        'UNIFORM_KMEANS_FAILURE',   6);

    S.fallbackReason = struct( ...
        'NONE',                    'NONE', ...
        'M_LE_3_OR_N_LT_50',       'M_LE_3_OR_N_LT_50', ...
        'FRONT1_LT_THRESHOLD',     'FRONT1_LT_THRESHOLD', ...
        'OBJECTIVE_RANGE_LT_1E12', 'OBJECTIVE_RANGE_LT_1E12', ...
        'NDSORT_EXCEPTION',        'NDSORT_EXCEPTION', ...
        'KMEANS_EXCEPTION',        'KMEANS_EXCEPTION');

    S.candidateModes = {'indicator','explore','fallback'};

    S.topLevelVariables = { ...
        'metadata','evaluations','snapshots','trajectory', ...
        'finalPopulation','IGD','IGDp','runtime','auditRuntime','validation'};

    S.metadataFields = { ...
        'schemaVersion','profile','behavior','problem','family','M', ...
        'requestedD','actualD','problemN','initialFE','maxFE','completedFE', ...
        'gmax','pMix','rGood','qKeep','lambda0','nMin','nMax', ...
        'run','seed','pairedKey','algorithmClass','frozenAlgorithmClass', ...
        'matlabVersion','computer','completedAt'};

    S.evaluationFields = {'EvalID','Decision','Objective','Generation'};

    S.snapshotFields = { ...
        'SnapshotID','Generation','FE','Ratio','Alpha', ...
        'PopulationEvalID','PopulationDec','PopulationObj', ...
        'RefEvalID','RefObj','kEff','Nref','Theta', ...
        'DirectionSource','FallbackReason', ...
        'Front1Count','ClusterCount','UniqueDirectionCount','V', ...
        'Delta','AnchorPositiveRate','AnchorNormalizedG','AnchorMargin', ...
        'LabelDyn','ScoreV','ScoreHybrid','CatalogCurrent', ...
        'ScoreVStd','LabelDynStd','EffectiveScaleRatio','TrainingCatalog'};

    S.trajectoryFields = { ...
        'Generation','FEBefore','FEAfter','CandidateMode', ...
        'SelectedEvalID','PopulationEvalIDAfter'};
end
