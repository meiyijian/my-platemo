function smoke_HES_EA_N100_M10(part,run,threads)
%One-run timing/validity smoke test for HES_EA_N100 at M=10.
%   Writes into a scratch folder so the real 10目标\n30 dataset stays clean.
%   RUN is used as a single-element vector so the harness runs exactly that
%   one run (a scalar would be expanded to 1:RUN by the harness).
    if nargin < 1 || isempty(part),    part    = 2;  end   % DTLZ2
    if nargin < 2 || isempty(run),     run     = 99; end
    if nargin < 3 || isempty(threads), threads = 1;  end
    maxNumCompThreads(threads);
    warning('off','stats:pdist2:ZeroPoints');   % benign cosine-angle noise

    thisFolder = fileparts(mfilename('fullpath'));
    platform   = fileparts(fileparts(thisFolder));
    addpath(fullfile(platform,'Experiments', ...
        'REMO_new2_AdaMaO_UniformMix_Pruned_FullSeries'));

    logFolder = fullfile(thisFolder,'logs');
    if ~isfolder(logFolder), mkdir(logFolder); end

    problems = {'DTLZ1','DTLZ2','DTLZ3','DTLZ4','DTLZ5','DTLZ6','DTLZ7', ...
                'WFG1','WFG2','WFG3','WFG4','WFG5','WFG6','WFG7','WFG8','WFG9'};

    runList = reshape(double(run),1,[]);   % always a vector: a scalar would be
                                           % expanded to 1:RUN by the harness
    run_UniformMixPrunedFullSeries(part,16, ...
        'OutputRoot','D:\REMOandDREMO测试集\_smoke_HESEA_M10', ...
        'FolderName','HES_EA_N100', ...
        'Algorithm','HES_EA_N100', ...
        'Problems',problems, ...
        'Runs',runList, ...
        'M',10, 'D',30, 'MaxFE',300, 'N',100, ...
        'Parameters',{}, ...
        'ExtraMetrics',{'IGDp'}, ...
        'SaveCount',30, ...
        'SeedBase',21260912, ...
        'SeedMode','deterministic', ...
        'PlatEMORoot',platform, ...
        'LogFile',fullfile(logFolder,sprintf('smoke_p%02d.log',part)), ...
        'SummaryCsvDir',logFolder, ...
        'Warmup',true);
end
