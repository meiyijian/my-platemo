function run_lkc_candidate_probe_suite(varargin)
% run_lkc_candidate_probe_suite - Preset DTLZ/WFG suites for LKC candidate probe.
%
% Recommended MATLAB commands:
%   run_lkc_candidate_probe_suite('preset', 'quick')
%   run_lkc_candidate_probe_suite('preset', 'mixed', 'runs', 5, 'maxFE', 300)
%   run_lkc_candidate_probe_suite('preset', 'full',  'runs', 10, 'maxFE', 500)
%   analyze_lkc_candidate_probe('fig', true)

    p = inputParser;
    p.addParameter('preset', 'mixed');
    p.addParameter('runs', []);
    p.addParameter('maxFE', []);
    p.addParameter('overwrite', false);
    p.parse(varargin{:});
    opt = p.Results;

    preset = lower(char(opt.preset));
    problems = makeProblemSet(preset);

    if isempty(opt.runs)
        switch preset
            case 'quick'
                runs = 1;
            case {'dtlz', 'wfg'}
                runs = 5;
            case 'full'
                runs = 10;
            otherwise
                runs = 3;
        end
    else
        runs = opt.runs;
    end

    if isempty(opt.maxFE)
        switch preset
            case 'quick'
                maxFE = 120;
            case 'full'
                maxFE = 500;
            otherwise
                maxFE = 300;
        end
    else
        maxFE = opt.maxFE;
    end

    fprintf('LKC candidate probe preset = %s\n', preset);
    fprintf('Problems = %d, runs = %d, maxFE = %d\n', numel(problems), runs, maxFE);
    printProblemSet(problems);

    run_lkc_candidate_probe( ...
        'problems', problems, ...
        'runs', runs, ...
        'maxFE', maxFE, ...
        'overwrite', opt.overwrite);
end


function problems = makeProblemSet(preset)
    switch preset
        case 'quick'
            problems = { ...
                {@DTLZ2, 5, 14}, ...
                {@WFG4,  5, 14}  ...
            };

        case 'dtlz'
            problems = { ...
                {@DTLZ2,  5, 14}, ...
                {@DTLZ3,  5, 14}, ...
                {@DTLZ4,  5, 14}, ...
                {@DTLZ7,  5, 24}, ...
                {@DTLZ2, 10, 19}, ...
                {@DTLZ3, 10, 19}, ...
                {@DTLZ4, 10, 19}, ...
                {@DTLZ7, 10, 29}  ...
            };

        case 'wfg'
            problems = { ...
                {@WFG1,  5, 14}, ...
                {@WFG4,  5, 14}, ...
                {@WFG6,  5, 14}, ...
                {@WFG9,  5, 14}, ...
                {@WFG1, 10, 19}, ...
                {@WFG4, 10, 19}, ...
                {@WFG6, 10, 19}, ...
                {@WFG9, 10, 19}  ...
            };

        case 'mixed'
            problems = { ...
                {@DTLZ2,  5, 14}, ...
                {@DTLZ3,  5, 14}, ...
                {@DTLZ7,  5, 24}, ...
                {@WFG1,   5, 14}, ...
                {@WFG4,   5, 14}, ...
                {@WFG9,   5, 14}, ...
                {@DTLZ2, 10, 19}, ...
                {@DTLZ3, 10, 19}, ...
                {@WFG4,  10, 19}, ...
                {@WFG9,  10, 19}  ...
            };

        case 'full'
            problems = { ...
                {@DTLZ1,  5, 14}, ...
                {@DTLZ2,  5, 14}, ...
                {@DTLZ3,  5, 14}, ...
                {@DTLZ4,  5, 14}, ...
                {@DTLZ7,  5, 24}, ...
                {@WFG1,   5, 14}, ...
                {@WFG2,   5, 14}, ...
                {@WFG4,   5, 14}, ...
                {@WFG6,   5, 14}, ...
                {@WFG9,   5, 14}, ...
                {@DTLZ1, 10, 19}, ...
                {@DTLZ2, 10, 19}, ...
                {@DTLZ3, 10, 19}, ...
                {@DTLZ4, 10, 19}, ...
                {@DTLZ7, 10, 29}, ...
                {@WFG1,  10, 19}, ...
                {@WFG2,  10, 19}, ...
                {@WFG4,  10, 19}, ...
                {@WFG6,  10, 19}, ...
                {@WFG9,  10, 19}  ...
            };

        otherwise
            error('Unknown preset "%s". Use quick, dtlz, wfg, mixed, or full.', preset);
    end
end


function printProblemSet(problems)
    for i = 1:numel(problems)
        spec = problems{i};
        fprintf('  %2d. %-6s M=%d D=%d\n', ...
            i, func2str(spec{1}), spec{2}, spec{3});
    end
end
