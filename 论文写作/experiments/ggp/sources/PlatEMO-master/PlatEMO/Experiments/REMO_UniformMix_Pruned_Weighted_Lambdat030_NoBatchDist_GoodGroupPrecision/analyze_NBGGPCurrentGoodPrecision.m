function outputs = analyze_NBGGPCurrentGoodPrecision()
%ANALYZE_NBGGPCURRENTGOODPRECISION Current-checkpoint convergence precision.
%   Reuses the completed formal GGP snapshots. At each checkpoint, the
%   25 solutions with the lowest benchmark-specific g form an independent
%   current-convergence reference set. The three views each select 25 of
%   the same 100 evaluated solutions. No optimization or objective
%   evaluation is performed here.
%
%   This is a relative convergence label, not a complete Pareto-quality
%   label. In particular, DTLZ7 also has disconnected Pareto regions.

    [pathInfo, pathCleanup] = NBGGPSetupPaths(); %#ok<ASGLU>
    protocol = NBGGPProtocol("formal");
    jobs = protocol.Jobs;
    if numel(jobs) ~= 160
        error("NBGGP:ProtocolDrift", "Expected 160 formal jobs.");
    end

    checkpointTemplate = struct( ...
        "Problem", "", "M", NaN, "Run", NaN, "Seed", NaN, ...
        "SnapshotID", NaN, "FE", NaN, "Stage", "", ...
        "N", NaN, "SelectedCount", NaN, "BoundaryTie", false, ...
        "HybridHits", NaN, "DirectionHits", NaN, "AnchorHits", NaN, ...
        "HybridPrecision", NaN, "DirectionPrecision", NaN, ...
        "AnchorPrecision", NaN);
    checkpointRows = repmat(checkpointTemplate, numel(jobs)*34, 1);
    runTemplate = struct( ...
        "Problem", "", "M", NaN, "Run", NaN, "Seed", NaN, ...
        "Checkpoints", NaN, "HybridPrecision", NaN, ...
        "DirectionPrecision", NaN, "AnchorPrecision", NaN, ...
        "HybridMinusDirection", NaN, "HybridMinusAnchor", NaN, ...
        "SourceFile", "");
    runRows = repmat(runTemplate, numel(jobs), 1);
    rowIndex = 0;

    for jobIndex = 1:numel(jobs)
        job = jobs(jobIndex);
        filePath = NBGGPResultPath(fullfile(pathInfo.ExperimentDirectory, ...
            "results"), "formal", job);
        if ~isfile(filePath)
            error("NBGGP:MissingRun", "Missing %s", filePath);
        end
        data = load(filePath, "metadata", "auditData");
        meta = data.metadata;
        if string(meta.Problem) ~= string(job.Problem) || ...
                meta.M ~= job.M || meta.Run ~= job.Run || ...
                meta.Seed ~= job.Seed || meta.ProblemN ~= 100 || ...
                meta.CompletedFE ~= 300 || meta.RGood ~= 0.25
            error("NBGGP:MetadataMismatch", "Unexpected metadata in %s", filePath);
        end
        snapshots = data.auditData.snapshots;
        if numel(snapshots) ~= 34
            error("NBGGP:SnapshotCount", "Expected 34 snapshots in %s", filePath);
        end
        runPrecision = zeros(numel(snapshots), 3);

        for snapshotIndex = 1:numel(snapshots)
            snapshot = snapshots(snapshotIndex);
            dec = double(snapshot.PopulationDec);
            n = size(dec, 1);
            if n ~= 100 || size(dec, 2) ~= meta.ActualD || ...
                    size(snapshot.PopulationObj, 1) ~= n || ...
                    size(snapshot.PopulationObj, 2) ~= meta.M
                error("NBGGP:SnapshotShape", "Invalid snapshot in %s", filePath);
            end
            goodCount = ceil(n*meta.RGood);
            g = benchmarkG(string(meta.Problem), dec, meta.M);
            if any(~isfinite(g))
                error("NBGGP:InvalidG", "Nonfinite g in %s", filePath);
            end
            [sortedG, gOrder] = sortrows([g, (1:n).']);
            oracle = false(n, 1);
            oracle(gOrder(1:goodCount)) = true;
            boundaryTie = sortedG(goodCount,1) == sortedG(goodCount+1,1);

            hybrid = logical(snapshot.CatalogCurrent(:));
            direction = topK(double(snapshot.ScoreV(:)), goodCount);
            anchor = topK(double(snapshot.AnchorMargin(:)), goodCount);
            if numel(hybrid) ~= n || nnz(hybrid) ~= goodCount || ...
                    ~isequal(hybrid, topK(double(snapshot.ScoreHybrid(:)), goodCount))
                error("NBGGP:SelectionMismatch", ...
                    "Hybrid selection does not match the saved catalog in %s", filePath);
            end
            hits = [nnz(hybrid & oracle), nnz(direction & oracle), ...
                nnz(anchor & oracle)];
            runPrecision(snapshotIndex,:) = hits/goodCount;

            rowIndex = rowIndex + 1;
            checkpointRows(rowIndex) = struct( ...
                "Problem", string(meta.Problem), "M", meta.M, ...
                "Run", meta.Run, "Seed", meta.Seed, ...
                "SnapshotID", snapshot.SnapshotID, "FE", snapshot.FE, ...
                "Stage", NBGGPStageBin(snapshot.Ratio), ...
                "N", n, "SelectedCount", goodCount, ...
                "BoundaryTie", boundaryTie, ...
                "HybridHits", hits(1), "DirectionHits", hits(2), ...
                "AnchorHits", hits(3), ...
                "HybridPrecision", runPrecision(snapshotIndex,1), ...
                "DirectionPrecision", runPrecision(snapshotIndex,2), ...
                "AnchorPrecision", runPrecision(snapshotIndex,3));
        end

        means = mean(runPrecision, 1);
        runRows(jobIndex) = struct( ...
            "Problem", string(meta.Problem), "M", meta.M, ...
            "Run", meta.Run, "Seed", meta.Seed, ...
            "Checkpoints", numel(snapshots), ...
            "HybridPrecision", means(1), ...
            "DirectionPrecision", means(2), ...
            "AnchorPrecision", means(3), ...
            "HybridMinusDirection", means(1)-means(2), ...
            "HybridMinusAnchor", means(1)-means(3), ...
            "SourceFile", string(filePath));
        if mod(jobIndex, 20) == 0
            fprintf("Current-good precision: %d/%d runs processed.\n", ...
                jobIndex, numel(jobs));
        end
    end

    checkpointTable = struct2table(checkpointRows(1:rowIndex));
    runTable = struct2table(runRows);
    if rowIndex ~= 5440 || any(checkpointTable.BoundaryTie)
        error("NBGGP:CoverageOrTie", ...
            "Expected 5440 checkpoints without g boundary ties; found %d rows and %d ties.", ...
            rowIndex, nnz(checkpointTable.BoundaryTie));
    end
    comparisons = compareRuns(runTable);
    stageSummary = summarizeStages(checkpointTable);
    outputDirectory = fullfile(pathInfo.ExperimentDirectory, ...
        "results", "analysis", "formal", "current_good_g");
    if ~isfolder(outputDirectory)
        mkdir(outputDirectory);
    end
    checkpointPath = fullfile(outputDirectory, "CurrentGood_Checkpoints.csv");
    runPath = fullfile(outputDirectory, "CurrentGood_PerRun.csv");
    comparisonPath = fullfile(outputDirectory, "CurrentGood_Comparisons.csv");
    stagePath = fullfile(outputDirectory, "CurrentGood_Stages.csv");
    writetable(checkpointTable, checkpointPath);
    writetable(runTable, runPath);
    writetable(comparisons, comparisonPath);
    writetable(stageSummary, stagePath);
    outputs = struct("CheckpointPath", checkpointPath, "RunPath", runPath, ...
        "ComparisonPath", comparisonPath, "StagePath", stagePath, ...
        "Checkpoints", checkpointTable, "Runs", runTable, ...
        "Comparisons", comparisons, "Stages", stageSummary);
    fprintf("Current-good precision complete: %d runs, %d checkpoints.\n", ...
        height(runTable), height(checkpointTable));
end

function g = benchmarkG(problem, dec, m)
    switch problem
        case {"DTLZ2", "DTLZ4", "DTLZ5"}
            g = sum((dec(:,m:end)-0.5).^2, 2);
        case "DTLZ7"
            g = 1+9*mean(dec(:,m:end), 2);
        otherwise
            error("NBGGP:UnsupportedProblem", "No g definition for %s", problem);
    end
end

function selected = topK(score, k)
    n = numel(score);
    if any(~isfinite(score)) || k > n
        error("NBGGP:InvalidScore", "Invalid score or quota.");
    end
    [~, order] = sortrows([-score(:), (1:n).']);
    selected = false(n, 1);
    selected(order(1:k)) = true;
end

function comparisons = compareRuns(runs)
    pairs = ["DirectionPrecision", "score_v"; ...
             "AnchorPrecision", "anchor_margin"];
    configurations = unique(runs(:, ["Problem", "M"]), "rows");
    template = struct("Problem", "", "M", NaN, "Baseline", "", ...
        "Runs", NaN, "PAQCMean", NaN, "BaselineMean", NaN, ...
        "DeltaPercentagePoints", NaN, "MedianDeltaPercentagePoints", NaN, ...
        "RunWins", NaN, "RunTies", NaN, "RunLosses", NaN, ...
        "PValueRaw", NaN, "PValueHolm", NaN, "RejectHolm05", false);
    rows = repmat(template, height(configurations)*size(pairs,1), 1);
    rowIndex = 0;
    for configIndex = 1:height(configurations)
        problem = configurations.Problem(configIndex);
        m = configurations.M(configIndex);
        subset = sortrows(runs(runs.Problem == problem & runs.M == m,:), "Run");
        if height(subset) ~= 20 || ~isequal(subset.Run, (1:20).')
            error("NBGGP:IncompleteRuns", "Incomplete runs for %s M%d", problem, m);
        end
        for pairIndex = 1:size(pairs,1)
            baseline = subset.(pairs(pairIndex,1));
            comparison = NBGGPComparePaired(subset.HybridPrecision, baseline);
            difference = subset.HybridPrecision-baseline;
            rowIndex = rowIndex+1;
            rows(rowIndex) = struct( ...
                "Problem", problem, "M", m, ...
                "Baseline", pairs(pairIndex,2), ...
                "Runs", comparison.NumberOfPairs, ...
                "PAQCMean", comparison.MeanA, ...
                "BaselineMean", comparison.MeanB, ...
                "DeltaPercentagePoints", 100*comparison.MeanDelta, ...
                "MedianDeltaPercentagePoints", 100*comparison.MedianDelta, ...
                "RunWins", nnz(difference > 0), ...
                "RunTies", nnz(difference == 0), ...
                "RunLosses", nnz(difference < 0), ...
                "PValueRaw", comparison.PValueRaw, ...
                "PValueHolm", NaN, "RejectHolm05", false);
        end
    end
    comparisons = struct2table(rows);
    comparisons.PValueHolm = NBGGPHolmAdjust(comparisons.PValueRaw);
    comparisons.RejectHolm05 = comparisons.PValueHolm <= 0.05 & ...
        comparisons.DeltaPercentagePoints > 0;
end

function summary = summarizeStages(checkpoints)
    [group, problem, m, run, stage] = findgroups( ...
        checkpoints.Problem, checkpoints.M, checkpoints.Run, checkpoints.Stage);
    perRunStage = table(problem, m, run, stage, ...
        splitapply(@mean, checkpoints.HybridPrecision, group), ...
        splitapply(@mean, checkpoints.DirectionPrecision, group), ...
        splitapply(@mean, checkpoints.AnchorPrecision, group), ...
        'VariableNames', {'Problem', 'M', 'Run', 'Stage', ...
        'Hybrid', 'Direction', 'Anchor'});
    [stageGroup, problem, m, stage] = findgroups( ...
        perRunStage.Problem, perRunStage.M, perRunStage.Stage);
    summary = table(problem, m, stage, ...
        splitapply(@numel, perRunStage.Run, stageGroup), ...
        splitapply(@mean, perRunStage.Hybrid, stageGroup), ...
        splitapply(@mean, perRunStage.Direction, stageGroup), ...
        splitapply(@mean, perRunStage.Anchor, stageGroup), ...
        'VariableNames', {'Problem', 'M', 'Stage', 'Runs', ...
        'PAQCMean', 'DirectionMean', 'AnchorMean'});
end
